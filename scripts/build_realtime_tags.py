"""
Phase 1 - Build semantic/realtime_tags.yaml from the exported CSV files.

OFFLINE: does not connect to the database. It reads:
  outputs/phase1/masters/Master_Plants.csv
  outputs/phase1/realtime/pidata_B.csv  (or pidata_A.csv if B is missing)

For every PI tag it works out: plant (resolving the mixed PlantCode / PlantCodeScada
codes), stage, unit, metric, unit of measure, and whether it is fresh, stale or dead
at the moment of the snapshot.

Run from the project folder:
    .\\.venv\\Scripts\\python.exe scripts\\build_realtime_tags.py
"""
import csv
import sys
from datetime import datetime
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.config import settings  # noqa: E402

PHASE1 = ROOT / "outputs" / "phase1"
OUT_FILE = ROOT / "semantic" / "realtime_tags.yaml"

METRICS = {
    "U": {"metric": "unit_gross_generation", "uom": "MW", "level": "unit"},
    "AG": {"metric": "stage_actual_generation", "uom": "MW", "level": "stage"},
    "FREQ": {"metric": "grid_frequency", "uom": "Hz", "level": "station"},
}


def read_csv(path: Path) -> list[dict]:
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def parse_dt(text: str):
    return datetime.fromisoformat(text) if text else None


def main() -> None:
    snapshot = PHASE1 / "realtime" / "pidata_B.csv"
    if not snapshot.exists():
        snapshot = PHASE1 / "realtime" / "pidata_A.csv"
    tags = read_csv(snapshot)
    plants = read_csv(PHASE1 / "masters" / "Master_Plants.csv")

    by_code = {p["PlantCode"]: p for p in plants}
    by_scada = {p["PlantCodeScada"]: p for p in plants if p["PlantCodeScada"]}

    # Snapshot time = newest UpdatedOn in the file (close to the server time of the query)
    snap_time = max(parse_dt(t["UpdatedOn"]) for t in tags if t["UpdatedOn"])
    fresh_limit = settings.live_freshness_minutes * 60

    result: dict[str, dict] = {}
    unresolved, counts = [], {"fresh": 0, "stale": 0, "dead": 0}
    for t in tags:
        code = t["PlantCode"]
        plant = by_code.get(code) or by_scada.get(code)
        if not plant:
            unresolved.append(code)
            continue
        kind = "U" if t["XMLTag"].startswith("U") else t["XMLTag"]
        info = METRICS.get(kind, {"metric": "unknown", "uom": "?", "level": "?"})
        ts = parse_dt(t["TimeStamp"])
        age_s = (snap_time - ts).total_seconds() if ts else None
        if age_s is not None and age_s <= fresh_limit:
            status = "fresh"
        elif age_s is not None and age_s <= 86400:
            status = "stale"
        else:
            status = "dead"
        counts[status] += 1

        entry = {
            "rid": int(t["RID"]),
            "pi_tag": t["PITag"],
            "metric": info["metric"],
            "uom": info["uom"],
            "stage": t["Stage"],
            "status": status,
            "last_timestamp": t["TimeStamp"] or None,
        }
        if info["level"] == "unit":
            entry["unit"] = t["Unit"]
        if t["comml"] == "0" and info["level"] == "unit":
            entry["commercial"] = False

        p = result.setdefault(plant["PlantCode"], {
            "name": plant["StationName"],
            "fuel": plant["EnergyType"],
            "capacity_mw": float(plant["GrossCapMW"] or 0),
            "pidata_plant_code": code,
            "tags": [],
        })
        p["tags"].append(entry)

    duplicates = 0
    for p in result.values():
        p["tags"].sort(key=lambda e: (e["metric"], e["stage"], e.get("unit", "")))
        p["fresh_tags"] = sum(e["status"] == "fresh" for e in p["tags"])
        p["has_live_generation"] = any(e["status"] == "fresh" and e["metric"] != "grid_frequency" for e in p["tags"])
        # Several tags can feed the SAME unit/stage value (main + backup tag, or old empty rows).
        groups: dict[tuple, list] = {}
        for e in p["tags"]:
            if e["metric"] != "grid_frequency":
                groups.setdefault((e["metric"], e["stage"], e.get("unit")), []).append(e["pi_tag"] or "(empty)")
        dups = [f"{stage} {unit or 'AG'}: {', '.join(tags)}" for (m, stage, unit), tags in groups.items() if len(tags) > 1]
        if dups:
            p["same_value_multiple_tags"] = dups
            duplicates += len(dups)

    doc = {
        "description": "PI tags in Data_RealTime_PIData mapped to plant / stage / unit / metric. "
                       "Generated by scripts/build_realtime_tags.py - do not edit by hand; re-run the script.",
        "source_snapshot": snapshot.name,
        "snapshot_time": snap_time.isoformat(sep=" ", timespec="seconds"),
        "freshness_minutes": settings.live_freshness_minutes,
        "status_meaning": {"fresh": f"TimeStamp within {settings.live_freshness_minutes} min - may be shown as live",
                           "stale": "older than the threshold but within 1 day - show only as 'last available value at <time>'",
                           "dead": "older than 1 day or no timestamp - never show as current"},
        "metrics": {v["metric"]: {"xml_tag": k if k != "U" else "U1..U13", "uom": v["uom"], "level": v["level"]} for k, v in METRICS.items()},
        "value_column": "PITag_Value (cleaned; negatives already set to 0). Never use PITag_Value_Raw.",
        "live_source_decision": (
            "Use XML_RealView (latest block of today) for live VALUES and TOTALS: it holds exactly one value per unit/stage. "
            "Do NOT sum Data_RealTime_PIData rows - many units have 2-3 tags (main + backup, or old empty rows), "
            "see same_value_multiple_tags. Use this file only to check which plants/units have a fresh feed."),
        "summary": {"tags": len(tags), **counts, "plants": len(result),
                    "plants_with_live_generation": sum(p["has_live_generation"] for p in result.values()),
                    "values_with_multiple_tags": duplicates,
                    "unresolved_plant_codes": sorted(set(unresolved))},
        "plants": dict(sorted(result.items())),
    }
    OUT_FILE.write_text(yaml.safe_dump(doc, sort_keys=False, allow_unicode=True, width=200), encoding="utf-8")
    print(f"Wrote {OUT_FILE}")
    print(yaml.safe_dump(doc["summary"], sort_keys=False))


if __name__ == "__main__":
    main()
